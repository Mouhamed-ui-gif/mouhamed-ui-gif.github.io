/* ---------------- BUSINESS PLAN ---------------- */
function genBP() {
  const t = dict().bp;
  const name = document.getElementById("bpName").value.trim();
  const cat = document.getElementById("bpCat").value;
  const city = document.getElementById("bpCity").value.trim();
  const budget = +document.getElementById("bpBudget").value || 0;
  const desc = document.getElementById("bpDesc").value.trim();
  const fmtM = (v) => v.toLocaleString("en-US") + " DA";

  const catText = {
    tech: [t.offer, `منصة أو تطبيق أو خدمة رقمية تخدم جمهوراً محدداً. ${desc}`, t.price, "نموذج اشتراك شهري + إصدار مجاني محدود", t.cost, ""],
    food: [t.offer, `قائمة طعام مميزة تركز على الجودة والتميز المحلي. ${desc}`, t.price, "تسعير متوسط السوق مع عروض مواسم", t.cost, ""],
    services: [t.offer, `خدمة مهنية بمستوى عالٍ وثقة العملاء. ${desc}`, t.price, "تسعير بالساعة أو بالاتفاق حسب المشروع", t.cost, ""],
    trade: [t.offer, `توفير منتجات مختارة بعناية مع خدمة توصيل سريعة. ${desc}`, t.price, "هامش ربح تنافسي 20-35%", t.cost, ""],
  }[cat];
  const [offer, offerV, price, priceV, costK, _cv] = catText;

  const costs = [
    [t.costL.setup, Math.round(budget * 0.5)],
    [t.costL.rent, Math.round(budget * 0.15)],
    [t.costL.staff, Math.round(budget * 0.2)],
    [t.costL.mkt, Math.round(budget * 0.15)],
  ];
  const costTxt = costs.map(([k, v]) => `${k}: ${fmtM(v)}`).join("\n");
  const rev = Math.round(budget * 0.4);

  const secs = [
    [t.sec.vision, `"${name}" — ${desc}\nالمدينة المستهدفة: ${city}`],
    [t.sec.market, `• الجمهور المستهدف: سكان ${city} والمحيط.\n• الميزة التنافسية: جودة + تخصيص + خدمة أسرع.\n• المنافسون: العروض الحالية في ${city}.`],
    [t.sec.offer, offerV],
    [t.sec.price, priceV],
    [t.sec.mkt, `• تواجد على إنستغرام وفيسبوك.\n• حملة إطلاق مع عروض خاصة.\n• شراكات مع مؤثرين محليين في ${city}.`],
    [t.sec.cost, costTxt + `\n(${t.revNote})`],
    [t.sec.rev, `إيراد شهري تقديري: ${fmtM(rev)}\n(${t.revNote})`],
    [t.sec.next, `1) تأكيد السوق بعينة تجريبية\n2) تجهيز مقر / منصة\n3) إطلاق رسمي وتجميع آراء العملاء`],
  ];

  const html = secs.map(([h, body]) => `<h4>${h}</h4>${body.replace(/\n/g, "<br>")}`).join("");
  const plain = t.planTxt + name + "\n================\n" + secs.map(([h, body]) => h + "\n" + body).join("\n\n");

  document.getElementById("bpText").innerHTML = html;
  document.getElementById("bpResult").hidden = false;
  document.querySelector(".bp-empty").hidden = true;
  return plain;
}

function dlText(name, text) {
  const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = (name || "file") + ".txt";
  a.click();
  URL.revokeObjectURL(a.href);
}

/* ---------------- STUDY ---------------- */
function renderCards() {
  const list = document.getElementById("cardList");
  const cards = JSON.parse(localStorage.getItem("mg-cards") || "[]");
  list.innerHTML = cards.length ? "" : `<li class="hint">—</li>`;
  cards.forEach((c, i) => {
    const li = document.createElement("li");
    li.innerHTML = `<span><b>${c[0]}</b> — ${c[1]}</span><button data-del="${i}" aria-label="del">🗑</button>`;
    list.appendChild(li);
  });
  list.querySelectorAll("[data-del]").forEach((b) => b.addEventListener("click", () => {
    const cards = JSON.parse(localStorage.getItem("mg-cards") || "[]");
    cards.splice(+b.dataset.del, 1);
    localStorage.setItem("mg-cards", JSON.stringify(cards));
    renderCards();
  }));
}

let quizIdx = -1;
function startQuiz() {
  const cards = JSON.parse(localStorage.getItem("mg-cards") || "[]");
  const t = dict().st;
  if (!cards.length) { document.getElementById("quizQ").textContent = t.noCards; return; }
  quizIdx = (Math.random() * cards.length) | 0;
  document.getElementById("quizQ").textContent = cards[quizIdx][0];
  document.getElementById("quizQ").dataset.answer = cards[quizIdx][1];
  document.getElementById("quizFlip").hidden = false;
  document.getElementById("quizNext").hidden = false;
}

