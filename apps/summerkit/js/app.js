/* ---------------- TRANSLATOR ---------------- */
function translate(text, from, to) {
  const t = dict().tr;
  text = text.trim().toLowerCase().replace(/[!؟?.,،]/g, "");
  const found = Object.entries(PHRASES).find(([, v]) => v[from].toLowerCase() === text);
  if (found) return found[1][to];
  return null;
}

