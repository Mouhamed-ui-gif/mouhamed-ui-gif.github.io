  const dirMap = { ar: "rtl", fr: "ltr", en: "ltr" };

  function apply(lang) {
    const dict = translations[lang] || translations.ar;
    const html = document.documentElement;
    html.lang = lang;
    html.dir = dirMap[lang] || "rtl";
    document.title = translations[lang]
      ? (lang === "ar"
          ? "محمد غناي | Mouhamed Ghennai — مطوّر ويب ورائد أعمال"
          : lang === "fr"
            ? "Mouhamed Ghennai — Développeur Web & Entrepreneur"
            : "Mouhamed Ghennai — Web Developer & Entrepreneur")
      : document.title;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const parts = key.split(".");
      let value = dict;
      for (const p of parts) value = value && value[p];
      if (value === undefined) return;
      if (Array.isArray(value)) {
        el.innerHTML = value.map((li) => "<li>" + li + "</li>").join("");
      } else {
        el.innerHTML = value;
      }
    });

    document.querySelectorAll("[data-lang]").forEach((btn) => {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
    });
  }

  function init() {
    let saved = "ar";
    try { saved = localStorage.getItem("mg-lang") || "ar"; } catch (e) {}
    if (!translations[saved]) saved = "ar";
    apply(saved);

    document.querySelectorAll("[data-lang]").forEach((btn) => {
      btn.addEventListener("click", () => {
        const lang = btn.getAttribute("data-lang");
        try { localStorage.setItem("mg-lang", lang); } catch (e) {}
        apply(lang);
      });
    });
  }

  document.addEventListener("DOMContentLoaded", init);
